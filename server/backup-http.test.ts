import test from 'node:test';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createGzip, gzipSync, gunzipSync } from 'node:zlib';
import { Readable } from 'node:stream';
import { MAX_BACKUP_BYTES, readBackupFile } from '../shared/backup.ts';
import { availableTestPort, waitForTestServer } from './test-server.ts';

test('backups larger than both former limits export and restore through JSON and gzip without changing source data', async t => {
  const directory = mkdtempSync(join(tmpdir(), 'mazal-backup-http-'));
  const port = await availableTestPort();
  const child = spawn(process.execPath, [fileURLToPath(new URL('./index.ts', import.meta.url))], { env: { ...process.env, PORT: String(port), MAZAL_DATA_DIR: directory }, stdio: ['ignore', 'pipe', 'pipe'] });
  t.after(async () => { if (child.exitCode === null) { const exited = new Promise<void>(resolve => child.once('exit', () => resolve())); child.kill('SIGTERM'); await exited; } rmSync(directory, { recursive: true, force: true }); });
  await waitForTestServer(child, 'Mazal server', 10000);
  const base = `http://127.0.0.1:${port}`;
  const backup = await (await fetch(`${base}/api/backup`)).json();
  backup.data.originalImports = [{ date: '2026-01-01T00:00:00.000Z', source: { preserved: 'x'.repeat(26 * 1024 * 1024) } }];
  const json = JSON.stringify(backup);
  assert.ok(Buffer.byteLength(json) > 25 * 1024 * 1024);
  assert.deepEqual(await readBackupFile(new Blob([json])), backup);
  const post = (body: string | Buffer, revision: number, type = 'application/json') => fetch(`${base}/api/backup/restore`, { method: 'POST', headers: { 'Content-Type': type, 'X-Mazal-Revision': String(revision) }, body: typeof body === "string" ? body : Uint8Array.from(body) });
  const restored = await post(json, 0);
  assert.equal(restored.status, 200, await restored.clone().text());
  const revision = (await restored.json()).revision;
  const exported = await fetch(`${base}/api/backup?format=gzip`);
  assert.equal(exported.headers.get('content-type'), 'application/gzip');
  const compressed = Buffer.from(await exported.arrayBuffer());
  const decoded = JSON.parse(gunzipSync(compressed).toString('utf8'));
  assert.deepEqual(decoded.data.originalImports, backup.data.originalImports);
  assert.equal((await post(compressed, revision, 'application/gzip')).status, 200);
  assert.equal((await post(gzipSync(json), revision, 'application/gzip')).status, 409);
  assert.equal((await post('broken JSON', revision + 1)).status, 400);
  assert.equal((await post(Buffer.from('broken gzip'), revision + 1, 'application/gzip')).status, 400);
  const wrongWorkspace = { ...backup, workspace: 'demo' };
  assert.equal((await post(JSON.stringify(wrongWorkspace), revision + 1)).status, 400);
  const oversizedChunks: Buffer[] = [];
  const padding = Buffer.alloc(1024 * 1024, 32);
  const oversized = Readable.from(Array.from({ length: MAX_BACKUP_BYTES / padding.length + 1 }, () => padding)).pipe(createGzip());
  for await (const chunk of oversized) oversizedChunks.push(chunk);
  const excessive = await post(Buffer.concat(oversizedChunks), revision + 1, 'application/gzip');
  assert.equal(excessive.status, 413);
  assert.match((await excessive.json()).error, /256 MiB/);
  const invalidUtf8 = Buffer.concat([Buffer.from('{"source":"'), Buffer.from([0xff]), Buffer.from('"}')]);
  assert.equal((await post(invalidUtf8, revision + 1)).status, 400);
  assert.equal((await post('{}', revision + 1, 'text/plain')).status, 415);
  const missingRevisionResponse = await fetch(`${base}/api/backup/restore`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: '{}' });
  assert.equal(missingRevisionResponse.status, 400);
  const unchanged = await (await fetch(`${base}/api/backup`)).json();
  assert.equal(unchanged.data.revision, revision + 1);
  assert.deepEqual(unchanged.data.originalImports, backup.data.originalImports);
  const smallBackup = { ...backup, data: { ...backup.data, originalImports: [] } };
  const legacyRestore = (expectedRevision?: number) => fetch(`${base}/api/command`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ type: 'restore', backup: smallBackup, expectedRevision }) });
  const missingRevision = await legacyRestore();
  assert.equal(missingRevision.status, 400);
  assert.match((await missingRevision.json()).error, /revision|Refresh/);
  assert.equal((await legacyRestore(revision)).status, 409);
  assert.equal((await (await fetch(`${base}/api/state`)).json()).revision, revision + 1);
  assert.equal((await legacyRestore(revision + 1)).status, 200);
  assert.equal((await fetch(`${base}/api/backup/restore`, { method: 'POST', headers: { Origin: 'https://attacker.example', 'Content-Type': 'application/json' }, body: '{}' })).status, 403);
});
