import test from 'node:test';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { gunzipSync } from 'node:zlib';
import { MAX_DOCUMENT_BYTES } from './documents.ts';

test('document HTTP workflow uploads, reviews, downloads, exports and isolates original files without changing financial records', async t => {
  const directory = mkdtempSync(join(tmpdir(), 'mazal-documents-http-'));
  const port = 30000 + Math.floor(Math.random() * 20000);
  const child = spawn(process.execPath, [fileURLToPath(new URL('./index.ts', import.meta.url))], { env: { ...process.env, PORT: String(port), MAZAL_DATA_DIR: directory }, stdio: ['ignore', 'pipe', 'pipe'] });
  t.after(async () => { if (child.exitCode === null) { const exited = new Promise<void>(resolve => child.once('exit', () => resolve())); child.kill('SIGTERM'); await exited; } rmSync(directory, { recursive: true, force: true }); });
  await new Promise<void>((resolve, reject) => {
    const timer = setTimeout(() => reject(new Error('Mazal document server did not start.')), 5000);
    child.stdout.once('data', () => { clearTimeout(timer); resolve(); });
    child.once('exit', code => { clearTimeout(timer); reject(new Error(`Mazal document server exited with ${code}.`)); });
  });
  const url = `http://127.0.0.1:${port}`;
  const initialFinance = await (await fetch(`${url}/api/state`)).json();
  const empty = await (await fetch(`${url}/api/documents`)).json();
  assert.equal(empty.documents.length, 0);
  assert.equal(empty.storage.limitPerFileBytes, MAX_DOCUMENT_BYTES);
  const pdf = Buffer.from('%PDF-1.7\nOriginal receipt bytes.\n%%EOF\n');
  const headers = { 'Content-Type': 'application/octet-stream', 'X-Mazal-Document': encodeURIComponent(JSON.stringify({ originalName: 'Vehicle receipt.pdf', kind: 'receipt', documentDate: '2026-09-24', amountCents: 12345, expenseUse: 'personal', merchant: 'Repair shop' })) };
  const upload = await fetch(`${url}/api/documents`, { method: 'POST', headers, body: pdf });
  assert.equal(upload.status, 201);
  const uploaded = await upload.json();
  assert.equal(uploaded.document.reviewStatus, 'needs_review');
  assert.equal(uploaded.document.expenseUse, 'personal');
  const duplicate = await fetch(`${url}/api/documents`, { method: 'POST', headers, body: pdf });
  assert.equal(duplicate.status, 200);
  assert.equal((await duplicate.json()).duplicate, true);
  const patch = await fetch(`${url}/api/documents/${uploaded.document.id}`, { method: 'PATCH', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ notes: 'Personal and commuting use. Source inspected.', reviewStatus: 'reviewed', expectedRevision: uploaded.document.revision }) });
  assert.equal(patch.status, 200);
  assert.equal((await patch.json()).document.reviewStatus, 'reviewed');
  const original = await fetch(`${url}/api/documents/${uploaded.document.id}/content`);
  assert.equal(original.status, 200);
  assert.equal(original.headers.get('content-type'), 'application/pdf');
  assert.equal(original.headers.get('x-content-type-options'), 'nosniff');
  assert.deepEqual(Buffer.from(await original.arrayBuffer()), pdf);
  const head = await fetch(`${url}/api/documents/${uploaded.document.id}/content`, { method: 'HEAD' });
  assert.equal(head.headers.get('content-length'), String(pdf.length));
  assert.equal((await head.arrayBuffer()).byteLength, 0);
  const download = await fetch(`${url}/api/documents/${uploaded.document.id}/content?download=1`);
  assert.match(download.headers.get('content-disposition')!, /^attachment/);
  await download.arrayBuffer();
  const archive = await fetch(`${url}/api/documents/export`);
  assert.equal(archive.status, 200);
  assert.match(archive.headers.get('content-disposition')!, /\.tar\.gz/);
  const tar = gunzipSync(Buffer.from(await archive.arrayBuffer()));
  assert.equal(tar.subarray(0, 13).toString('ascii'), 'manifest.json');
  assert.ok(tar.includes(pdf));
  assert.ok(tar.includes(Buffer.from('"reviewStatus": "reviewed"')));
  assert.equal((await fetch(`${url}/api/documents/${uploaded.document.id}/content?workspace=demo`)).status, 404);
  assert.equal((await (await fetch(`${url}/api/documents?workspace=demo`)).json()).documents.length, 0);
  assert.deepEqual(await (await fetch(`${url}/api/state`)).json(), initialFinance);
  const command = (body: unknown) => fetch(`${url}/api/command`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) });
  const added = await command({ type: 'add_account', entityId: 'personal', name: 'Card', accountType: 'debt', openingBalanceCents: 10000, openingDate: '2026-01-01', expectedRevision: initialFinance.revision, requestId: 'create-card' });
  assert.equal(added.status, 200);
  const addedState = await added.json();
  const accountId = addedState.accounts[0].id;
  const statement = { id: 'registered-statement', accountId, sourceFile: uploaded.document.originalName, sha256: uploaded.document.sha256, periodStart: '2026-01-01', periodEnd: '2026-01-31', openingBalanceCents: 10000, closingBalanceCents: 10000, rows: [] };
  const imported = await command({ type: 'stage_statement', statement, requestId: 'register-source', expectedRevision: addedState.revision });
  assert.equal(imported.status, 200);
  for (const suffix of ['', `&sha=${uploaded.document.sha256}`]) {
    const linkedSource = await fetch(`${url}/api/source?file=${encodeURIComponent(statement.sourceFile)}${suffix}`);
    assert.equal(linkedSource.status, 200);
    assert.deepEqual(Buffer.from(await linkedSource.arrayBuffer()), pdf);
  }
  assert.equal((await fetch(`${url}/api/source?file=${encodeURIComponent(statement.sourceFile)}&sha=${'f'.repeat(64)}`)).status, 404);
  assert.equal((await fetch(`${url}/api/source?file=Unregistered.pdf&sha=${uploaded.document.sha256}`)).status, 404);
  writeFileSync(join(directory, 'documents', 'live', `${uploaded.document.id}.original`), 'Changed original');
  const damagedArchive = await fetch(`${url}/api/documents/export`);
  assert.equal(damagedArchive.status, 500);
  assert.match(damagedArchive.headers.get('content-type')!, /^application\/json/);
  assert.equal(damagedArchive.headers.get('content-disposition'), null);
  assert.match((await damagedArchive.json()).error, /SHA-256/);
});

test('document HTTP upload rejects spoofed signatures, invalid metadata, oversized bodies and cross-origin access', async t => {
  const directory = mkdtempSync(join(tmpdir(), 'mazal-documents-rejections-'));
  const port = 30000 + Math.floor(Math.random() * 20000);
  const child = spawn(process.execPath, [fileURLToPath(new URL('./index.ts', import.meta.url))], { env: { ...process.env, PORT: String(port), MAZAL_DATA_DIR: directory }, stdio: ['ignore', 'pipe', 'pipe'] });
  t.after(async () => { if (child.exitCode === null) { const exited = new Promise<void>(resolve => child.once('exit', () => resolve())); child.kill('SIGTERM'); await exited; } rmSync(directory, { recursive: true, force: true }); });
  await new Promise<void>((resolve, reject) => {
    const timer = setTimeout(() => reject(new Error('Mazal document server did not start.')), 5000);
    child.stdout.once('data', () => { clearTimeout(timer); resolve(); });
    child.once('exit', code => { clearTimeout(timer); reject(new Error(`Mazal document server exited with ${code}.`)); });
  });
  const url = `http://127.0.0.1:${port}/api/documents`;
  const headers = { 'Content-Type': 'application/octet-stream', 'X-Mazal-Document': encodeURIComponent(JSON.stringify({ originalName: 'Statement.pdf', kind: 'statement' })) };
  assert.equal((await fetch(url, { method: 'POST', headers, body: '<html>not PDF</html>' })).status, 415);
  assert.equal((await fetch(url, { method: 'POST', headers: { ...headers, 'X-Mazal-Document': '%bad percent' }, body: '%PDF-1.7' })).status, 400);
  assert.equal((await fetch(url, { method: 'POST', headers: { ...headers, 'Content-Type': 'application/json' }, body: '{}' })).status, 415);
  assert.equal((await fetch(url, { method: 'POST', headers: { ...headers, Origin: 'https://attacker.example' }, body: '%PDF-1.7' })).status, 403);
  assert.equal((await fetch(url, { headers: { 'Sec-Fetch-Site': 'cross-site' } })).status, 403);
  const oversized = Buffer.alloc(MAX_DOCUMENT_BYTES + 1);
  oversized.write('%PDF-1.7');
  const rejected = await fetch(url, { method: 'POST', headers, body: oversized });
  assert.equal(rejected.status, 413);
  assert.match((await rejected.json()).error, /exceeds/);
  assert.equal((await (await fetch(url)).json()).documents.length, 0);
});
