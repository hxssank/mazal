import assert from 'node:assert/strict';
import { execFile } from 'node:child_process';
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import test from 'node:test';
import { fileURLToPath } from 'node:url';
import { promisify } from 'node:util';
import type { AppState } from '../shared/types.ts';
import { inspectWorkbook } from './workbook-inspect.ts';

const execute = promisify(execFile);

for (const layout of [6, 8]) test(`upgrading workbook layout ${layout} adds transaction context and retains unrelated worksheets, values, styles, formulas and tables`, { timeout: 180000 }, async t => {
  const directory = await mkdtemp(join(tmpdir(), 'mazal-workbook-migration-'));
  t.after(() => rm(directory, { recursive: true, force: true }));
  const existing = join(directory, 'previous.xlsx');
  const output = join(directory, 'updated.xlsx');
  const input = join(directory, 'snapshot.json');
  const create = join(directory, 'create.mjs');
  await writeFile(create, `import { Workbook } from ${JSON.stringify(new URL('../scripts/workbook-runtime.mjs', import.meta.url).href)};
const book = Workbook.create();
const home = book.worksheets.add('Home');
home.getRange('D3').values = [['Mazal layout ${layout}']];
home.getRange('A1').values = [['Outdated generated home']];
const transactions = book.worksheets.add('Transactions');
transactions.getRange('A5:L6').values = [['Date', 'Account', 'Description', 'Type', 'Amount', 'Category', 'To account', 'Statement', 'Source', 'Posted', 'Transaction ID', 'Imported category'], ['2026-01-10', 'Card', 'BANK ORIGINAL', 'Expense', 12.34, 'Bills', '', '', 'Manual entry', '', 'transaction-1', 'Bills']];
transactions.tables.add('A5:L6', true, 'TableTransactions');
const notes = book.worksheets.add('Personal notes');
notes.getRange('A1:B3').values = [['Private notes', 'Amount'], ['Keep this value', 12.34], ['Second note', 4.56]];
notes.getRange('A1:B1').format = {fill:'#112233',font:{bold:true,color:'#FFFFFF'}};
notes.getRange('B2:B4').setNumberFormat('0.00');
notes.getRange('B4').formulas = [['=SUM(B2:B3)']];
notes.tables.add('A1:B3', true, 'PersonalNotes');
notes.freezePanes.freezeRows(1);
await book.write(process.argv[2]);
`);
  await execute(process.execPath, [create, existing]);
  const before = await inspectWorkbook(existing);
  const beforeBytes = await readFile(existing);
  const state: AppState = { workspace: 'live', revision: 1, entities: [{ id: 'personal', name: 'Personal', kind: 'personal', ownershipBps: 10000 }], accounts: [{ id: 'card', entityId: 'personal', name: 'Card', type: 'debt', currency: 'CAD', balanceCents: 1234, reconciledAt: null }], transactions: [{ id: 'transaction-1', date: '2026-01-10', description: 'BANK ORIGINAL', displayName: 'Home internet', note: 'Monthly service for the apartment', kind: 'expense', amountCents: 1234, accountId: 'card', toAccountId: null, category: 'Bills', source: 'Manual entry', createdAt: '2026-01-10T12:00:00.000Z' }], obligations: [], reserves: [], positions: [], audit: [], lastBackupAt: null };
  await writeFile(input, JSON.stringify({ state, documents: [], generatedAt: '2026-09-25T12:00:00.000Z' }));
  const { stdout } = await execute(process.execPath, [fileURLToPath(new URL('../scripts/build-workbook.mjs', import.meta.url)), '--input', input, '--output', output, '--existing', existing], { timeout: 170000 });
  const summary = JSON.parse(stdout.trim().split('\n').at(-1)!);
  const after = await inspectWorkbook(output);
  assert.equal(summary.updateMode, 'migration');
  assert.deepEqual(after.sheets['Personal notes'].cells, before.sheets['Personal notes'].cells);
  assert.deepEqual(after.sheets['Personal notes'].pane, before.sheets['Personal notes'].pane);
  assert.deepEqual(after.tables.PersonalNotes.headers, before.tables.PersonalNotes.headers);
  assert.deepEqual(after.tables.PersonalNotes.rows, before.tables.PersonalNotes.rows);
  assert.deepEqual(after.tables.PersonalNotes.style, before.tables.PersonalNotes.style);
  assert.equal(after.sheets.Home.cells.A1.value, 'Home');
  assert.equal(after.sheets.Home.cells.D3.value, 'Mazal layout 10');
  assert.equal(before.tables.TableTransactions.headers.length, 12);
  assert.equal(after.tables.TableTransactions.headers.length, 14);
  assert.equal(after.tables.TableTransactions.rows[0].Description.value, 'BANK ORIGINAL');
  assert.equal(after.tables.TableTransactions.rows[0].Name.value, 'Home internet');
  assert.equal(after.tables.TableTransactions.rows[0].Notes.value, 'Monthly service for the apartment');
  assert.deepEqual(await readFile(existing), beforeBytes);
});
