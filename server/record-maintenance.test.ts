function setup(t:{after:(fn:()=>void)=>void}){
  const directory=mkdtempSync(join(tmpdir(),'mazal-record-maintenance-')),store=createStore(join(directory,'live.sqlite'),'live');
  t.after(()=>{store.close();rmSync(directory,{recursive:true,force:true});});
  const command=(input:Command)=>store.command({...input,expectedRevision:store.state().revision});
  command({type:'add_account',entityId:'personal',name:'Cash',accountType:'cash',openingBalanceCents:100000,openingDate:'2026-01-01'});
  const account=store.state().accounts[0].id;
  return {store,command,account};
}
test('manual correction keeps exact reversal, replaces amount, retries safely, and survives restore validation',t=>{
  const {store,command,account}=setup(t);
  command({type:'add_transaction',accountId:account,kind:'expense',amountCents:1200,date:today(),description:'Lunch',category:'Food',requestId:'expense'});
  const original=store.state().transactions.find(tx=>tx.description==='Lunch')!;
  const correction:Command={type:'correct_transaction',id:original.id,reason:'Receipt amount was 10 dollars',replacement:{accountId:account,kind:'expense',amountCents:1000,date:today(),description:'Lunch corrected',category:'Food'},requestId:'correction'};
  command(correction);command(correction);
  const state=store.state();
  assert.equal(state.accounts[0].balanceCents,99000);
  assert.equal(state.transactions.filter(tx=>tx.reversalOf===original.id).length,1);
  assert.equal(state.transactions.find(tx=>tx.reversalOf===original.id)?.amountCents,-1200);
  assert.equal(state.transactions.find(tx=>tx.replacesId===original.id)?.amountCents,1000);
  const backup=store.export();assert.doesNotThrow(()=>store.command({type:'restore',backup}));
  assert.throws(()=>command({...correction,requestId:'second'}),/already has a reversal/);
});
test('amount corrections preserve the saved reporting category until the user changes category',t=>{
  const {store,command,account}=setup(t);
  command({type:'add_transaction',accountId:account,kind:'expense',amountCents:1200,date:today(),description:'Internet',category:'Digital',requestId:'expense'});
  const original=store.state().transactions.find(tx=>tx.description==='Internet')!;
  command({type:'categorize_transaction',id:original.id,expectedCategory:'Digital',category:'Digital',expenseCategory:'Bills',requestId:'report-category'});
  const corrected=command({type:'correct_transaction',id:original.id,reason:'Receipt amount was 10 dollars',replacement:{accountId:account,kind:'expense',amountCents:1000,date:today(),description:'Internet corrected',category:'Digital'},requestId:'correction'}).transactions.find(tx=>tx.replacesId===original.id)!;
  assert.equal(corrected.expenseCategory,'Bills');
  const state=store.state(),match=transactionCategoryMatcher(state,'personal',categoryLimits(state,'personal'));
  assert.equal(state.transactions.filter(tx=>tx.kind==='expense'&&match(tx).name==='Bills').reduce((sum,tx)=>sum+tx.amountCents,0),1000);
  assert.equal(state.transactions.filter(tx=>tx.kind==='expense'&&match(tx).name==='Digital').reduce((sum,tx)=>sum+tx.amountCents,0),0);
  store.restore(store.export());
  assert.equal(store.state().transactions.find(tx=>tx.id===corrected.id)?.expenseCategory,'Bills');
  const reclassified=command({type:'correct_transaction',id:corrected.id,reason:'Correct category',replacement:{accountId:account,kind:'expense',amountCents:1000,date:today(),description:'Internet for work',category:'Career'},requestId:'reclassify'}).transactions.find(tx=>tx.replacesId===corrected.id)!;
  const latest=store.state();
  assert.equal(transactionCategoryMatcher(latest,'personal',categoryLimits(latest,'personal'))(reclassified).name,'Career');
  assert.equal(latest.accounts[0].balanceCents,99000);
  assert.doesNotThrow(()=>store.restore(store.export()));
});
