test('matching a bill advances its due date without changing cash or the original source',t=>{
  const {store,command,account}=setup(t);
  command({type:'add_transaction',accountId:account,kind:'expense',amountCents:1750,date:today(),description:'Phone',category:'Bills',requestId:'expense'});
  const tx=store.state().transactions.find(tx=>tx.description==='Phone')!;
  command({type:'add_obligation',entityId:'personal',name:'Phone bill',amountCents:2000,dueDate:today(),direction:'out',recurrence:'monthly',accountId:account,category:'Bills',requestId:'bill'});
  const bill=store.state().obligations[0],before=store.state().accounts[0].balanceCents,count=store.state().transactions.length;
  command({type:'pay_obligation',id:bill.id,expectedDueDate:bill.dueDate,transactionId:tx.id,requestId:'match'});
  assert.equal(store.state().accounts[0].balanceCents,before);assert.equal(store.state().transactions.length,count);
  assert.equal(store.state().transactions.find(item=>item.id===tx.id)?.source,'Manual entry');
  assert.ok(store.state().obligations[0].dueDate>bill.dueDate);
  assert.throws(()=>command({type:'pay_obligation',id:bill.id,expectedDueDate:store.state().obligations[0].dueDate,transactionId:tx.id,requestId:'match-again'}),/already linked/);
});
test('a refunded bill occurrence stays recorded and its linked payment cannot be reversed',t=>{
  const {store,command,account}=setup(t);
  command({type:'add_transaction',accountId:account,kind:'expense',amountCents:1750,date:today(),description:'Phone',category:'Bills',requestId:'expense'});
  const tx=store.state().transactions.find(tx=>tx.description==='Phone')!;
  command({type:'add_obligation',entityId:'personal',name:'Phone bill',amountCents:1750,dueDate:today(),direction:'out',recurrence:'monthly',accountId:account,category:'Bills',requestId:'bill'});
  const bill=store.state().obligations[0];
  command({type:'pay_obligation',id:bill.id,expectedDueDate:bill.dueDate,transactionId:tx.id,requestId:'match'});
  const linked=store.state();
  assert.throws(()=>command({type:'correct_transaction',id:tx.id,reason:'Undo linked payment',requestId:'reverse-linked'}),/Only unlinked manual entries/);
  assert.deepEqual(store.state(),linked);
  command({type:'record_refund',id:tx.id,accountId:account,amountCents:1750,date:today(),reason:'Full refund',requestId:'refund'});
  const refunded=store.state(),next=refunded.obligations[0];
  assert.equal(refunded.accounts[0].balanceCents,100000);
  assert.throws(()=>command({type:'update_obligation',id:bill.id,expectedStatus:'planned',expectedDueDate:next.dueDate,name:bill.name,amountCents:bill.amountCents,dueDate:bill.dueDate,recurrence:bill.recurrence,accountId:account,category:bill.category,requestId:'reuse-refunded-date'}),/already recorded/);
  assert.deepEqual(store.state(),refunded);
  assert.doesNotThrow(()=>store.restore(store.export()));
});
test('reversing an unlinked expense leaves its bill available for a replacement payment',t=>{
  const {store,command,account}=setup(t);
  command({type:'add_transaction',accountId:account,kind:'expense',amountCents:1750,date:today(),description:'Phone',category:'Bills',requestId:'expense'});
  const original=store.state().transactions.find(tx=>tx.description==='Phone')!;
  command({type:'add_obligation',entityId:'personal',name:'Phone bill',amountCents:1750,dueDate:today(),direction:'out',recurrence:'monthly',accountId:account,category:'Bills',requestId:'bill'});
  const bill=store.state().obligations[0];
  command({type:'correct_transaction',id:original.id,reason:'Correct amount',replacement:{accountId:account,kind:'expense',amountCents:1700,date:today(),description:'Corrected phone',category:'Bills'},requestId:'correct'});
  const replacement=store.state().transactions.find(tx=>tx.replacesId===original.id)!;
  command({type:'update_obligation',id:bill.id,expectedStatus:'planned',expectedDueDate:bill.dueDate,name:bill.name,amountCents:1700,dueDate:bill.dueDate,recurrence:bill.recurrence,accountId:account,category:bill.category,requestId:'correct-plan'});
  const before=store.state();
  assert.throws(()=>command({type:'pay_obligation',id:bill.id,expectedDueDate:bill.dueDate,transactionId:original.id,requestId:'match-reversed'}),/already linked or reversed/);
  assert.deepEqual(store.state(),before);
  command({type:'pay_obligation',id:bill.id,expectedDueDate:bill.dueDate,transactionId:replacement.id,requestId:'match-replacement'});
  assert.equal(store.state().accounts[0].balanceCents,98300);
  assert.equal(store.state().transactions.filter(tx=>tx.plannedPayment).length,1);
  assert.deepEqual(store.state().transactions.find(tx=>tx.id===replacement.id)?.plannedPayment,{obligationId:bill.id,dueDate:bill.dueDate});
  assert.doesNotThrow(()=>store.restore(store.export()));
});
