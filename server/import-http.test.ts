import test from 'node:test';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import type { AppState } from '../shared/types.ts';

test('HTTP stages only saved originals, commits reviewed rows, paginates, and exports an unchanged snapshot', async t => {
  const directory = mkdtempSync(join(tmpdir(), 'mazal-import-http-'));
  const port = 30000 + Math.floor(Math.random() * 20000);
  const child = spawn(process.execPath, [fileURLToPath(new URL('./index.ts', import.meta.url))], { env: { ...process.env, PORT: String(port), MAZAL_DATA_DIR: directory, MAZAL_MASTER_WORKBOOK: join(directory, 'export.xlsx') }, stdio: ['ignore', 'pipe', 'pipe'] });
  t.after(async () => { if (child.exitCode === null) { const exit = new Promise<void>(resolve => child.once('exit', () => resolve())); child.kill('SIGTERM'); await exit; } rmSync(directory, { recursive: true, force: true }); });
  await new Promise<void>((resolve, reject) => {
    const timer = setTimeout(() => reject(new Error('Import test server did not start.')), 8000);
    child.stdout.once('data', () => { clearTimeout(timer); resolve(); });
    child.once('exit', code => { clearTimeout(timer); reject(new Error(`Import test server exited with ${code}.`)); });
  });
  const url = `http://127.0.0.1:${port}`;
  const command = (body: unknown) => fetch(`${url}/api/command`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) });
  let state: AppState = await (await command({ type: 'add_account', entityId: 'personal', name: 'Test chequing', accountType: 'cash', openingBalanceCents: 10000, openingDate: '2025-01-01', expectedRevision: 0, requestId: 'create-chequing' })).json();
  const accountId = state.accounts[0].id;
  const source = { id: 'bank-jan', accountId, sourceFile: 'Bank.pdf', sha256: 'a'.repeat(64), periodStart: '2025-01-01', periodEnd: '2025-01-31', openingBalanceCents: 10000, closingBalanceCents: 8000, rows: [{ id: 'row-1', transactionDate: '2025-01-02', postingDate: '2025-01-03', description: 'Groceries', amountCents: -2000, sourcePage: 1 }] };
  const missing = await command({ type: 'stage_statement', statement: source, requestId: 'missing-original', expectedRevision: state.revision });
  assert.equal(missing.status, 404);
  const upload = await fetch(`${url}/api/documents`, { method: 'POST', headers: { 'Content-Type': 'application/octet-stream', 'X-Mazal-Document': encodeURIComponent(JSON.stringify({ originalName: 'Bank.pdf', kind: 'statement', accountId })) }, body: '%PDF-1.4\nSynthetic test statement' });
  assert.equal(upload.status, 201);
  source.sha256 = (await upload.json()).document.sha256;
  const stage = await command({ type: 'stage_statement', statement: source, requestId: 'stage-bank', expectedRevision: state.revision });
  assert.equal(stage.status, 200);
  state = await stage.json();
  assert.equal(state.accounts[0].balanceCents, 10000);
  assert.equal(state.transactions.length, 1);
  const premature = await command({ type: 'commit_statements', importIds: [source.id], requestId: 'too-soon', expectedRevision: state.revision });
  assert.equal(premature.status, 400);
  const reviewed = await command({ type: 'review_statement', importId: source.id, decisions: [{ rowId: 'row-1', kind: 'expense', category: 'Groceries' }], requestId: 'review-bank', expectedRevision: state.revision });
  assert.equal(reviewed.status, 200);
  state = await reviewed.json();
  const committed = await command({ type: 'commit_statements', importIds: [source.id], requestId: 'commit-bank', expectedRevision: state.revision });
  assert.equal(committed.status, 200);
  state = await committed.json();
  assert.equal(state.accounts[0].balanceCents, 8000);
  assert.equal(state.transactions.filter(item => item.kind === 'expense').length, 1);
  const page = await (await fetch(`${url}/api/transactions?accountId=${accountId}&kind=expense&limit=1&offset=0`)).json();
  assert.equal(page.total, 1);
  assert.equal(page.rows[0].description, 'Groceries');
  assert.equal(page.amountCents, 2000);
  assert.equal((await fetch(`${url}/api/transactions?limit=501`)).status, 400);
  assert.equal((await fetch(`${url}/api/transactions`, { method: 'POST' })).status, 405);
  const snapshot = await (await fetch(`${url}/api/workbook-data`)).json();
  assert.deepEqual(snapshot.state, state);
  assert.equal(snapshot.documents.length, 1);
  const legacy = await command({ type: 'import_rows', accountId, rows: [{ date: '2025-02-01', description: 'Card payment', amountCents: -100 }], requestId: 'legacy-csv' });
  assert.equal(legacy.status, 400);
  assert.deepEqual(await (await fetch(`${url}/api/state`)).json(), state);
  const withCard = await (await command({ type: 'add_account', entityId: 'personal', name: 'Card', accountType: 'debt', openingBalanceCents: 10000, openingDate: '2025-01-01', expectedRevision: state.revision, requestId: 'create-card' })).json();
  const bypass = await command({ type: 'import_statement', requestId: 'unreviewed-statement', statement: { ...source, id: 'legacy-card', accountId: withCard.accounts.find((item: { name: string }) => item.name === 'Card').id, sha256: 'b'.repeat(64), closingBalanceCents: 12000, rows: [{ ...source.rows[0], amountCents: 2000, kind: 'purchase', category: 'Groceries' }] } });
  assert.equal(bypass.status, 400);
  assert.match((await bypass.json()).error, /review/);
  assert.deepEqual(await (await fetch(`${url}/api/state`)).json(), withCard);
});
